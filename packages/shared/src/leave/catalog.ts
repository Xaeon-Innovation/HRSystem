export function defaultBalanceFor(
  employeeId: string,
  type: LeaveType,
  now = `${todayIso()}T08:00:00.000Z`,
  openingBalance = 0,
): LeaveBalance {
  const opening = type.tracksBalance ? openingBalance : 0;
  const row: LeaveBalance = {
    id: `bal-${employeeId}-${type.id}`,
    employeeId,
    leaveTypeId: type.id,
    openingBalance: opening,
    accrued: 0,
    carryOver: 0,
    adjustments: 0,
    used: 0,
    pending: 0,
    remaining: opening,
    negativeAllowed: type.code === "emergency",
    lastAccrualAt: type.tracksBalance ? now : null,
    updatedAt: now,
  };
  row.remaining = computeRemaining(row);
  return row;
}

