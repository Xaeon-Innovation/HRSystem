export function defaultRecordFor(employee: CompEmployee): CompensationRecord {
  const role = employee.role.toLowerCase();
  let payStructure: CompensationRecord["payStructure"] = "monthly";
  let baseAmount = 12000;
  let gradeId: string | null = "band-g3";
  let payFrequency: CompensationRecord["payFrequency"] = "monthly";
  if (role.includes("driver") || role.includes("field")) {
    payStructure = "hourly";
    baseAmount = 55;
    gradeId = "band-g2";
  } else if (role.includes("account") || role.includes("sales")) {
    payStructure = "salary_plus_commission";
    baseAmount = 15000;
    gradeId = "band-g4-ae";
  } else if (role.includes("coord")) {
    payStructure = "monthly";
    baseAmount = 16000;
    gradeId = "band-g4-ops";
  } else if (role.includes("people") || role.includes("hr")) {
    payStructure = "monthly";
    baseAmount = 20000;
    gradeId = "band-g6";
  }
  return {
    id: `rec-${employee.id}`,
    employeeId: employee.id,
    payStructure,
    baseAmount,
    currency: "EGP",
    payFrequency,
    hoursPerWeek: 40,
    workingDaysPerMonth: 22,
    effectiveDate: employee.hireDate,
    status: "active",
    gradeId,
    notes: "Generated from employee record",
    updatedAt: new Date().toISOString(),
  };
}

export function departmentFromTitle(title: string): string {
  const t = title.toLowerCase();
  if (t.includes("sales") || t.includes("account")) return "Sales";
  if (t.includes("ops") || t.includes("driver") || t.includes("field") || t.includes("coord")) {
    return "Operations";
  }
  if (t.includes("people") || t.includes("hr") || t.includes("admin")) return "People";
  return "General";
}
