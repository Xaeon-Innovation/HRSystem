function hist(
  id: string,
  employeeId: string,
  previousAmount: number,
  newAmount: number,
  extra: Omit<
    SalaryHistoryEntry,
    "id" | "employeeId" | "previousAmount" | "newAmount" | "changeAmount" | "changePercent" | "reasonCode"
  > & { reasonCode?: SalaryHistoryEntry["reasonCode"] },
): SalaryHistoryEntry {
  const delta = changeDelta(previousAmount, newAmount);
  return {
    id,
    employeeId,
    previousAmount,
    newAmount,
    changeAmount: delta.changeAmount,
    changePercent: delta.changePercent,
    reasonCode: extra.reasonCode ?? extra.changeType,
    ...extra,
  };
}

