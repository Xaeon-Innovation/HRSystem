function seedClockShifts(): ClockShift[] {
  const rows: ClockShift[] = [];
  let n = 1;
  const add = (
    employeeId: string,
    day: string,
    inHour: number,
    outHour: number,
    outMin = 0,
  ) => {
    rows.push({
      id: `clk-${employeeId}-${n++}`,
      employeeId,
      clockInAt: `${day}T${String(inHour).padStart(2, "0")}:00:00.000+03:00`,
      clockOutAt: `${day}T${String(outHour).padStart(2, "0")}:${String(outMin).padStart(2, "0")}:00.000+03:00`,
    });
  };
  const weekdays: string[] = [];
  for (let d = 1; d <= 28; d++) {
    const iso = `2026-08-${String(d).padStart(2, "0")}`;
    const dow = new Date(`${iso}T12:00:00+03:00`).getDay();
    if (dow !== 5 && dow !== 6) weekdays.push(iso);
  }
  for (const day of weekdays) {
    const extra =
      day.endsWith("06") || day.endsWith("13") || day.endsWith("20") || day.endsWith("27") ? 2 : 0;
    add("emp-youssef", day, 8, 16 + extra);
    add("emp-omar", day, 7, extra ? 18 : 16);
  }
  return rows;
}

