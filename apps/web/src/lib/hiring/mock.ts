function stagePath(
  steps: Array<{ stage: CandidateStage; enteredAt: string; leftAt?: string | null; by?: string }>,
  current: CandidateStage,
): StageHistoryEntry[] {
  return steps.map((s, i) => ({
    stage: s.stage,
    enteredAt: s.enteredAt,
    leftAt: s.leftAt ?? (s.stage === current && i === steps.length - 1 ? null : s.leftAt ?? null),
    movedById: s.by ?? "emp-karim",
    movedByName: s.by === "emp-nour" ? "Nour Adel" : "Karim Said",
  }));
}

function note(
  candidateId: string,
  id: string,
  body: string,
  at: string,
  visibility: CandidateNote["visibility"] = "recruiter",
  author: { id: string; name: string } = { id: "emp-karim", name: "Karim Said" },
): CandidateNote {
  return {
    id,
    candidateId,
    visibility,
    authorId: author.id,
    authorName: author.name,
    body,
    mentionPlaceholder: body.includes("@"),
    createdAt: at,
  };
}

function resume(candidateId: string, name: string, at: string): CandidateAttachment {
  return {
    id: `${candidateId}-cv`,
    candidateId,
    name: `${name.replace(/\s+/g, "-").toLowerCase()}-cv.pdf`,
    kind: "resume",
    url: `#resume-${candidateId}`,
    uploadedByName: "Karim Said",
    uploadedAt: at,
  };
}

