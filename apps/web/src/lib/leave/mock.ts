export function defaultBalanceFor(
  employeeId: string,
  type: LeaveType,
  now = `${todayIso()}T08:00:00.000Z`,
): LeaveBalance {
  const opening = type.tracksBalance ? (type.id.includes("annual") ? 0 : 0) : 0;
  const row: LeaveBalance = {
    id: `bal-${employeeId}-${type.id}`,
    employeeId,
    leaveTypeId: type.id,
    openingBalance: opening,
    accrued: 0,
    carryOver: 0,
    adjustments: 0,
    used: 0,
    pending: 0,
    remaining: 0,
    negativeAllowed: type.code === "emergency",
    lastAccrualAt: null,
    updatedAt: now,
  };
  row.remaining = computeRemaining(row);
  return row;
}

