function bal(
  employeeId: string,
  leaveTypeId: string,
  parts: Omit<LeaveBalance, "id" | "employeeId" | "leaveTypeId" | "remaining" | "updatedAt">,
): LeaveBalance {
  const row: LeaveBalance = {
    id: `bal-${employeeId}-${leaveTypeId}`,
    employeeId,
    leaveTypeId,
    remaining: 0,
    updatedAt: "2026-08-01T08:00:00.000Z",
    ...parts,
  };
  row.remaining = computeRemaining(row);
  return row;
}

