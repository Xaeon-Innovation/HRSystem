def unescape_js_string(raw: str) -> str:
    """Decode JS string escapes without mangling UTF-8 punctuation (· … —)."""
    try:
        return ast.literal_eval(f'"{raw}"')
    except Exception:
        return raw.replace(r"\"", '"').replace(r"\\", "\\")


def collect_keys() -> list[str]:
    keys: set[str] = set()
    pat = re.compile(r'\bt\(\s*"((?:[^"\\]|\\.)*)"')
    for p in list(ROOT.rglob("*.ts")) + list(ROOT.rglob("*.tsx")):
        if "/i18n/" in str(p):
            continue
        text = p.read_text(encoding="utf-8")
        for m in pat.finditer(text):
            keys.add(unescape_js_string(m.group(1)))
    extra = [
        "{n} day",
        "{n} days",
        "{n}m ago",
        "{n}h ago",
        "{n}d ago",
        "{n} min",
        "{n} h",
        "Employee",
        "Leave",
        "KPI & performance",
        "Attendance",
        "Payroll",
        "System",
        "Custom",
        "Info",
        "Warning",
        "Critical",
        "In-app",
        "Email",
        "Digest email",
    ]
    keys.update(extra)
    return sorted(keys)


def fallback(en: str) -> str:
    return EXACT.get(en, en)


def main() -> None:
    keys = collect_keys()
    lines = [
        "/** Arabic UI copy. English source strings are the keys. Layout stays LTR. */",
        "export const ar: Record<string, string> = {",
    ]
    for k in keys:
        ar = EXACT.get(k) or fallback(k)
        if ar == k and len(k) > 2:
            # still include identity so missing keys are visible in reviews
            continue
        lines.append(f"  {json.dumps(k, ensure_ascii=False)}: {json.dumps(ar, ensure_ascii=False)},")
    # always include exact even if not currently referenced
    for k, v in EXACT.items():
        # already added if in keys
        if k not in keys:
            lines.append(f"  {json.dumps(k, ensure_ascii=False)}: {json.dumps(v, ensure_ascii=False)},")
    lines.append("};")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    translated = sum(1 for k in keys if EXACT.get(k) or fallback(k) != k)
    print(f"wrote {OUT} keys={len(keys)} translated={translated} exact={len(EXACT)}")


if __name__ == "__main__":
    main()
